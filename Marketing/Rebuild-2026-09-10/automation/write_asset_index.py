#!/usr/bin/env python3
"""Generates ASSET_INDEX.md from what is actually on disk.

Written by a script rather than by hand so the index cannot claim a file that is not
there, or miss one that is. Re-run it after adding anything.

Usage:  write_asset_index.py [rebuild-root]
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

# Directory → what it is for. Anything not listed still appears, under "Other".
SECTIONS = [
    ("audit", "Audit — what is true, and what may therefore be said"),
    ("strategy", "Strategy — the position and the language that comes from it"),
    ("app-store", "App Store — the listing, the images and the preview"),
    ("website", "Website — copy to hand to a web project (nothing is deployed)"),
    ("social", "Social and launch"),
    ("press-kit", "Press kit"),
    ("feature-catalog", "Feature catalogue and security"),
    ("automation", "Automation — how the images are made and checked"),
]

# Files that are inputs or scratch rather than deliverables.
SKIP_DIRS = {"build", "raw-screenshots", "__pycache__", "fixture"}


def describe(path: Path, root: Path) -> str:
    """A one-line note for the files where the name is not self-explanatory."""
    notes = {
        "PRODUCT_TRUTH_MATRIX.md": "201 capabilities, each with a status, the code, and the test",
        "CLAIMS_MATRIX.md": "every approved claim (C1–C24), its EN/ZH wording and its evidence",
        "COMPETITOR_DIFFERENTIATION.md": "internal only; never published",
        "LEGACY_ASSET_AUDIT.md": "what happened to each 2026-08/09 asset, and why",
        "POSITIONING.md": "the product name, the differentiators, the Cloudflare decision",
        "MESSAGING_SYSTEM.md": "boilerplate at four lengths, EN and ZH, plus the vocabulary",
        "AUDIENCE_MATRIX.md": "nine audiences, what each is told, and the anti-audience",
        "SCREENSHOT_PLAN.md": "the eight screens and why each is there",
        "SCREENSHOT_DESIGN.md": "the visual system; two layouts, not one scaled",
        "SCREENSHOT_MANIFEST.json": "one record per image: source, SHA-256, feature, evidence",
        "CAPTURE_GUIDE.md": "how to reproduce the images, and the nine defects found doing it",
        "FINAL_VERIFICATION_REPORT.md": "the closing account of what was checked and what is blocked",
        "CLOUDFLARE_OVERVIEW.md": "internal only; nothing here may be used publicly yet",
        "FEATURE_COMPARISON.md": "internal only; no public comparison table is produced",
        "capture.sh": "builds the app, starts four servers, drives the real interface",
        "Render.swift": "lays captures onto the canvases; refuses to render an overflowing caption",
        "validate.py": "sizes, alpha, stretch, freshness, field limits, claims, secrets",
        "write_manifest.py": "generates SCREENSHOT_MANIFEST.json",
        "write_asset_index.py": "generates this index",
        "render_truth_matrix.py": "generates PRODUCT_TRUTH_MATRIX.md from the audit",
        "shotlist.json": "the eight captions, in three languages",
        "audit-results.json": "the raw audit output the truth matrix is rendered from",
        "collect_attachments.py": "(shared with the previous pipeline) exports the captures",
    }
    return notes.get(path.name, "")


def human(size: int) -> str:
    for unit in ("B", "KB", "MB"):
        if size < 1024 or unit == "MB":
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1024.0
    return ""


def main() -> int:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
    repo = root.parent.parent

    def files_in(directory: str) -> list[Path]:
        base = root / directory
        if not base.exists():
            return []
        found = []
        for path in sorted(base.rglob("*")):
            if not path.is_file():
                continue
            if any(part in SKIP_DIRS for part in path.relative_to(base).parts):
                continue
            if path.name == ".DS_Store":
                continue
            found.append(path)
        return found

    out: list[str] = []
    add = out.append
    add("# Asset index — Apex Terminal, 2026-09-10 rebuild\n")
    add(
        "Generated by `automation/write_asset_index.py` from what is on disk, so it cannot\n"
        "list a file that is not there. Paths are relative to the repository root.\n"
    )

    # The images get their own summary, because there are 72 of them.
    shots = sorted((root / "app-store/screenshots").rglob("*.png"))
    raws = sorted((root / "app-store/raw-screenshots").rglob("*.png"))
    sheets = sorted((root / "app-store/preview").glob("*.png"))
    add("## The images\n")
    add("| | Count | Where |")
    add("| --- | ---: | --- |")
    add(f"| **Store-ready screenshots** | {len(shots)} | `Marketing/Rebuild-2026-09-10/app-store/screenshots/<locale>/<slot>/` |")
    add(f"| Untouched captures | {len(raws)} | `…/app-store/raw-screenshots/<device>/<locale>/` |")
    add(f"| Contact sheets | {len(sheets)} | `…/app-store/preview/` |")
    add("")
    add("| Localization | iPhone 6.9\" | iPhone 6.5\" | iPad 13\" |")
    add("| --- | ---: | ---: | ---: |")
    for locale in ("en-US", "zh-Hans", "zh-Hant"):
        counts = [
            len(list((root / f"app-store/screenshots/{locale}/{slot}").glob("*.png")))
            for slot in ("iphone-6.9", "iphone-6.5", "ipad-13")
        ]
        add(f"| `{locale}` | {counts[0]} | {counts[1]} | {counts[2]} |")
    add("")

    for directory, title in SECTIONS:
        found = [p for p in files_in(directory) if p.suffix != ".png"]
        if not found:
            continue
        add(f"## {title}\n")
        add("| File | Size | Note |")
        add("| --- | ---: | --- |")
        for path in found:
            rel = path.relative_to(repo)
            add(f"| `{rel}` | {human(path.stat().st_size)} | {describe(path, root)} |")
        add("")

    add("## Not part of this rebuild\n")
    add(
        "`Marketing/AppStore/` is the previous set, from before the rename. It is left\n"
        "untouched and still runs. Its per-file verdicts are in\n"
        "[`audit/LEGACY_ASSET_AUDIT.md`](audit/LEGACY_ASSET_AUDIT.md) — in short, its 36\n"
        "finished images are unusable because the app's own name is inside the captured\n"
        "pixels, and its copy predates most of what the product can now do.\n"
    )

    (root / "ASSET_INDEX.md").write_text("\n".join(out) + "\n")
    total = sum(1 for _ in root.rglob("*") if _.is_file())
    print(f"  → ASSET_INDEX.md ({len(shots)} store images, {total} files in the tree)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
