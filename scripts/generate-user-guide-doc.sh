#!/usr/bin/env bash
#
# Writes docs/USER_GUIDE.md from the English guide the app ships.
#
# One source, two readers: the app parses App/Resources/Guide/guide-en.md into topics,
# and somebody reading the repository wants one page. Generating the second from the
# first is what keeps them from disagreeing — CI regenerates and fails on a difference,
# the same way the vendored patch is kept honest.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

python3 - <<'PY'
import re

source = open("App/Resources/Guide/guide-en.md").read()
# The topic markers are the app's structure, not the reader's: drop them, keep the order.
body = re.sub(r"<!-- topic:[^>]*-->\n", "", source)
# The illustration markers *are* content — the app draws a picture there (D-080). Left as
# comments they would be invisible here, so this page would silently have less in it than
# the app does. Named instead, so a reader of the repository knows what is missing.
body = re.sub(
    r"<!-- illustration:\s*([^>]*?)\s*-->",
    lambda m: f"> **In the app:** a drawn illustration of {m.group(1).replace('-', ' ')} appears here.",
    body,
).strip("\n")

header = """<!-- Generated by scripts/generate-user-guide-doc.sh. Edit App/Resources/Guide/guide-en.md. -->

# Apex Terminal — User Guide

This is the guide the app shows under **Settings → Help → User Guide**, and with ⌘/ from
any session. It is generated from `App/Resources/Guide/guide-en.md`, which is the file the
app parses, so the two cannot drift apart. The same guide ships in Simplified and
Traditional Chinese as `guide-zh-Hans.md` and `guide-zh-Hant.md`; all three carry the same
topics in the same order, which a test checks.

"""

open("docs/USER_GUIDE.md", "w").write(header + body + "\n")
print("wrote docs/USER_GUIDE.md")
PY
